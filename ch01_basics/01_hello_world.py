"""1.1 Hello, World: your first Python program.

Real-world comparison: a program is a recipe. Python reads it
top to bottom, one line at a time, like a cook following steps.

Run it:  python 01_hello_world.py
"""

# print() shows text on the screen. Text goes inside quotes.
print("Hello, World!")

# Each line runs in order, top to bottom.
print("Step 1: boil water")
print("Step 2: add tea leaves")
print("Step 3: pour and enjoy")

# print() can take several values; it puts a space between them.
print("Python", "is", "fun")

# sep= changes the separator, end= changes what comes after the line.
print("2026", "10", "24", sep="-")
print("Loading", end="...")
print("done")

# An empty print() gives you a blank line.
print()
print("You just ran your first Python program.")
